"""OpenVEX triage. A decision applies only where its scope, author and content allow.

Statements must name the exact component version. Unknown authors, generated
statements and out-of-scope contexts stay visible but do not change a finding.
Signatures are not verified here, so provenance always says authenticated: false.
"""
from ..common import purl as purls
from ..common.errors import UntrustedInputError
from ..common.safety import MIB, read_json, sha256_file
from ..readiness.checks import parse_time, vex_problem


def load_documents(paths):
    """Return (documents, problems). An unreadable file is a problem, not an empty decision set."""
    documents, problems = [], []
    for path in paths:
        try:
            document = read_json(path, 16 * MIB)
            if not isinstance(document, dict) or not str(document.get("@context", "")).startswith("https://openvex.dev/ns") or not isinstance(document.get("statements"), list):
                raise UntrustedInputError("vex_invalid", "not an OpenVEX document")
        except UntrustedInputError as exc:
            problems.append({"code": "vex_unreadable", "subject": str(path), "message": str(exc)})
            continue
        documents.append({"document": document, "file": str(path).rsplit("/", 1)[-1], "sha256": sha256_file(path)})
    return documents, problems


def _ids(entries):
    out = []
    for entry in entries or []:
        if isinstance(entry, dict) and isinstance(entry.get("@id"), str):
            out.append(entry["@id"])
    return out


def _versioned(identifier):
    parsed = purls.parse(identifier)
    return bool(parsed and parsed["version"])


def _scope_match(statement, product_purl, component_purl):
    """Return (matched, scope kind). Only exact, versioned identities match."""
    for product in statement.get("products") or []:
        if not isinstance(product, dict) or not isinstance(product.get("@id"), str):
            continue
        identifier = purls.strip(product["@id"])
        children = [purls.strip(item) for item in _ids(product.get("subcomponents"))]
        if identifier == product_purl and _versioned(identifier) and component_purl in children and _versioned(component_purl):
            return True, "product_and_component"
        if identifier == component_purl and _versioned(identifier) and not children:
            return True, "component_only"
    return False, ""


def _context_problem(statement, finding, now):
    scope = statement.get("x_cra_scope")
    if scope is None:
        return ""
    if not isinstance(scope, dict):
        return "x_cra_scope must be an object"
    expires = scope.get("expires")
    if expires is not None:
        moment = parse_time(expires)
        if moment is None:
            return "x_cra_scope.expires is not a date"
        if moment < now:
            return f"the decision expired on {expires}"
    configurations = scope.get("configurations")
    if configurations is not None and not set(finding["configurations"]) <= set(configurations):
        return "the finding appears in configurations the decision does not cover"
    artifacts = scope.get("artifacts")
    if artifacts is not None and not set(finding["artifacts"]) <= set(artifacts):
        return "the finding appears in artifacts the decision does not cover"
    return ""


def decide(finding, product_purl, documents, trusted_authors, now):
    """Return the triage decision for a finding, including statements that were not applied."""
    names = {finding["vulnerability"]["id"], *finding["vulnerability"]["aliases"]}
    applicable, rejected = [], []
    component_purl = finding["component"]["purl"]
    for item in documents:
        document = item["document"]
        author = document.get("author") if isinstance(document.get("author"), str) else ""
        for statement in document["statements"]:
            if not isinstance(statement, dict):
                continue
            vulnerability = statement.get("vulnerability")
            name = vulnerability.get("name") if isinstance(vulnerability, dict) else vulnerability
            if name not in names:
                continue
            matched, scope = _scope_match(statement, product_purl, component_purl)
            if not matched:
                continue
            provenance = {"document": item["file"], "document_sha256": item["sha256"], "author": author,
                          "timestamp": statement.get("timestamp") or document.get("timestamp"), "authenticated": False, "scope": scope}
            reason = vex_problem(statement)
            generated = statement.get("x_cra_generated_by") or document.get("x_cra_generated_by")
            if not reason and generated:
                reason = f"generated by {generated}; generated statements cannot become trusted decisions"
            if not reason and author not in trusted_authors:
                reason = f"author {author!r} is not in the policy's trusted VEX authors"
            if not reason:
                reason = _context_problem(statement, finding, now)
            if reason:
                rejected.append({"status": statement.get("status"), "reason": reason, "provenance": provenance})
            else:
                applicable.append((parse_time(provenance["timestamp"]), statement, provenance))
    decision = {"status": "needs_triage", "justification": "", "statement": "", "provenance": None, "rejected_statements": rejected, "problem": ""}
    if not applicable:
        if rejected:
            decision["problem"] = rejected[0]["reason"]
        return decision
    applicable.sort(key=lambda row: (row[0] is not None, row[0] or now))
    latest = applicable[-1]
    ties = [row for row in applicable if row[0] == latest[0] and row[1].get("status") != latest[1].get("status")]
    if ties or latest[0] is None:
        decision["problem"] = "several VEX statements disagree and none is clearly latest"
        return decision
    statement = latest[1]
    decision.update(status=statement.get("status"), justification=statement.get("justification") or "",
                    statement=statement.get("impact_statement") or statement.get("action_statement") or statement.get("status_notes") or "",
                    provenance=latest[2], superseded=len(applicable) - 1)
    return decision
